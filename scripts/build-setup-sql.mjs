/**
 * Regenerates supabase/setup/01-complete-schema.sql from the migrations.
 *
 * The migrations remain authoritative. This file exists only so the system can
 * be installed from the Supabase dashboard by someone who does not want to
 * install the CLI. Run this after changing any migration, and commit both.
 *
 *   npm run build:setup-sql
 */
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import { join } from 'node:path'

const MIGRATIONS = 'supabase/migrations'
const OUTPUT = 'supabase/setup/01-complete-schema.sql'

const header = `-- =====================================================================
-- COMPLETE SCHEMA SETUP  —  paste-once install for the Supabase SQL Editor
--
-- This is every migration in supabase/migrations/, concatenated in order.
-- It exists so the system can be installed entirely from the web dashboard,
-- with no terminal and no Supabase CLI.
--
-- HOW TO USE
--   1. Supabase Dashboard -> SQL Editor -> New query
--   2. Paste this whole file
--   3. Run
--   4. Expect "Success. No rows returned"
--
-- Safe to run more than once. Every statement is idempotent, so if it fails
-- partway you can fix the cause and run the whole file again.
--
-- DO NOT EDIT THIS FILE. It is generated from the migrations by
-- scripts/build-setup-sql.mjs. Edit a migration, then regenerate.
-- =====================================================================

`

const files = (await readdir(MIGRATIONS)).filter((f) => f.endsWith('.sql')).sort()

const body = await Promise.all(
  files.map(async (name) => {
    const sql = await readFile(join(MIGRATIONS, name), 'utf8')
    return [
      '',
      '',
      '-- #####################################################################',
      `-- # BEGIN ${name}`,
      '-- #####################################################################',
      '',
      sql,
      `-- # END ${name}`,
    ].join('\n')
  }),
)

const footer = `

-- =====================================================================
-- Done. Verify with the queries in docs/WEB-SETUP.md, Step 5.
-- =====================================================================
`

await mkdir('supabase/setup', { recursive: true })
await writeFile(OUTPUT, header + body.join('') + footer)

console.log(`Setup SQL built from ${files.length} migrations: ${OUTPUT}`)
